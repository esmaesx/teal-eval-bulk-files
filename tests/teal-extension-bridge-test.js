"use strict";

const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");

const root = path.join(__dirname, "..", "extension");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "manifest.json"), "utf8"));
const testManifest = JSON.parse(fs.readFileSync(path.join(__dirname, "test-manifest.json"), "utf8"));
const script = fs.readFileSync(path.join(root, "content.js"), "utf8");

assert.equal(fs.existsSync(path.join(root, "download-bridge.js")), false);
assert.equal(manifest.content_scripts.length, 1);
assert.equal(manifest.content_scripts[0].world, undefined);
assert.deepEqual(manifest.content_scripts[0].js, ["zip-builder.js", "bridge-plan-store.js", "delete-apply-envelope.js", "upload-lifetime.js", "content.js"]);
assert.equal(testManifest.version, manifest.version, "the checked-in local test manifest version must match the release manifest");
assert.deepEqual(testManifest.content_scripts[0].js, manifest.content_scripts[0].js, "the checked-in local test manifest must keep every required content script in release order");
assert.match(script, /attachShadow\(\{ mode: "closed" \}\)/);
assert.equal(/window\.confirm/.test(script), false);
assert.match(script, /event\.isTrusted\) closeConfirmation\(true\)/);
assert.equal((script.match(/options\.fromBridge \? true : await requestBatchConfirmation/g) || []).length, 2);
assert.match(script, /TealEvalBridgePlanStore\.createStore/);
assert.equal((script.match(/bridgePlanStore\.consume\(\{ authorizationId: command\.authorizationId/g) || []).length, 3);
const applyUploadBlock = script.match(/if \(command\.command === "apply-upload"\) \{([\s\S]*?)\n    \}/)?.[1] || "";
const applyDeleteBlock = script.match(/if \(command\.command === "apply-delete"\) \{([\s\S]*?)\n    \}/)?.[1] || "";
const applyDownloadBlock = script.match(/if \(command\.command === "apply-download"\) \{([\s\S]*?)\n    \}/)?.[1] || "";
assert.match(applyUploadBlock, /bridgePlanStore\.consume/);
assert.doesNotMatch(applyUploadBlock, /planUploadFromNames/);
assert.match(applyDeleteBlock, /bridgePlanStore\.consume/);
assert.match(applyDeleteBlock, /TealEvalDeleteApply\.executeDeleteApply/);
assert.match(applyDeleteBlock, /readInventory: publicInventory/);
assert.doesNotMatch(applyDeleteBlock, /planDeleteFromNames/);
assert.match(applyDownloadBlock, /bridgePlanStore\.consume/);
assert.match(applyDownloadBlock, /operation: "download"/);
assert.match(applyDownloadBlock, /startDownload\(\{ rows: plan\.rows, fromBridge: true \}\)/);
assert.doesNotMatch(applyDownloadBlock, /planDownloadFromNames|requestBatchConfirmation|\.click\(|confirm/i);
assert.match(script, /\["plan-upload", "plan-download", "plan-delete"\]/);
assert.match(script, /\["apply-upload", "apply-download", "apply-delete"\]/);
assert.match(script, /function strictStagedObservation\(\)/);
assert.match(script, /TealEvalDeleteApply\.observeReadyInventory/);
assert.match(script, /return strictStagedObservation\(\)\.inventory/);
assert.equal((script.match(/const observation = strictStagedObservation\(\)/g) || []).length, 3);
assert.match(script, /classifyUploads\(files, observation\.rows\)/);
assert.equal((script.match(/matches = observation\.rows\.filter/g) || []).length, 2);
assert.match(script, /!nativeListIsLoading\(panel\)/);
assert.match(script, /const readyRows = readNativeRowsFromPanel\(panel\)/);
assert.match(script, /readyRows\.some\(\(row\) => row\.filename === file\.name\)/);
assert.ok(script.indexOf("readyRows.some((row) => row.filename === file.name)") < script.indexOf("panel.nativeInput.files = transfer.files"));
assert.match(script, /const batchDeadline = Date\.now\(\) \+ UPLOAD_BATCH_TIMEOUT_MS/);
assert.match(script, /failed: unprocessedNames\.map\(\(name\) => \(\{ name, error \}\)\)/);
assert.match(script, /remaining: unprocessedNames/);
assert.equal((script.match(/A bulk operation is already running\./g) || []).length >= 3, true);
assert.match(script, /if \(options\.fromBridge\)/);
assert.match(script, /uploadSelectionReleased: true/);
assert.match(script, /options\.files\.length = 0/);
assert.match(script, /uploadQueue\.length = 0/);
assert.match(script, /teal-eval-bulk-command-v1/);
assert.match(script, /const INDETERMINATE_BLOB_RETENTION_MS = 15 \* 60 \* 1000/);
assert.match(script, /retainIndeterminateBlobUrl\(blobUrl\)/);
assert.match(script, /window\.addEventListener\("pagehide", revokeAllRetainedBlobUrls, \{ once: true \}\)/);
assert.match(script, /class="cli-bridge-surface"[^>]*tabindex="-1"/);
assert.match(script, /class="cli-bridge-upload"[^>]*tabindex="-1"/);
assert.match(script, /ui\.bridgeUploadInput\.addEventListener\("change",[\s\S]*?armBridgeUploadSelectionTimer\(\)/);
assert.match(script, /class="cli-bridge-command"[^>]*tabindex="-1"/);
assert.match(script, /ui\.bridgeCommandInput\.blur\(\)/);
assert.match(script, /ui\.bridgeUploadInput\.blur\(\)/);
assert.doesNotMatch(script, /class="cli-bridge-surface"[^>]*aria-hidden="true"/);
console.log("isolated bridge contract tests passed");
